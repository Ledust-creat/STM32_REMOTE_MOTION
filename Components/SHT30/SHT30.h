#ifndef SHT30_H
#define SHT30_H

#include <stdbool.h>
#include <stdint.h>

/*
*********************************************************************************************************
*   宏定义
*********************************************************************************************************
*/

#define SHT30_I2C_ADDRESS_7BIT    (0x44U)  /* 常见模块的 ADDR 引脚接地 */

/*
*********************************************************************************************************
*   类型定义
*********************************************************************************************************
*/

typedef struct
{
    int16_t temperature_centi_c;       /* 温度，单位 0.01 摄氏度 */
    uint16_t humidity_centi_percent;   /* 相对湿度，单位 0.01 %RH */
    uint32_t sample_tick_ms;           /* 有效采样完成时的 HAL 系统节拍 */
    bool valid;                         /* 仅 I2C 通信和两组 CRC 均通过时为 true */
} SHT30_Sample_t;

/*
*********************************************************************************************************
*   函数声明
*********************************************************************************************************
*/

bool SHT30_Init(void);
bool SHT30_ReadSingleShot(SHT30_Sample_t *sample);

#endif /* SHT30_H */
