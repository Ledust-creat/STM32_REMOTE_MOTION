#include "RCWL0515_Port.h"

#include "main.h"

/*
*********************************************************************************************************
*   函数定义
*********************************************************************************************************
*/

/*
*********************************************************************************************************
*   函 数 名: RCWL0515_Port_ReadMotionLevel
*   功能说明: 读取由 CubeMX 配置的 RCWL-0515 OUT 输入电平
*   返 回 值: true 表示 OUT 为高电平；false 表示 OUT 为低电平
*********************************************************************************************************
*/
bool RCWL0515_Port_ReadMotionLevel(void)
{
    return HAL_GPIO_ReadPin(RCWL_0515_GPIO_Port, RCWL_0515_Pin) == GPIO_PIN_SET;
}

/*
*********************************************************************************************************
*   函 数 名: RCWL0515_Port_EnterCritical
*   功能说明: 保存当前全局中断状态并关闭中断，保护事件标志和时间戳的一致性
*   返 回 值: 调用前的 PRIMASK 状态，必须传回 RCWL0515_Port_ExitCritical
*********************************************************************************************************
*/
uint32_t RCWL0515_Port_EnterCritical(void)
{
    uint32_t interrupt_state = __get_PRIMASK();

    __disable_irq();
    return interrupt_state;
}

/*
*********************************************************************************************************
*   函 数 名: RCWL0515_Port_ExitCritical
*   功能说明: 按进入临界区前的状态恢复全局中断，避免误开启调用者原本关闭的中断
*   形    参: interrupt_state - RCWL0515_Port_EnterCritical 返回的 PRIMASK 状态
*   返 回 值: 无
*********************************************************************************************************
*/
void RCWL0515_Port_ExitCritical(uint32_t interrupt_state)
{
    if (interrupt_state == 0U)
    {
        __enable_irq();
    }
}
